// Dot-path type: only accepts strings that exist in the FR dictionary.
type PathsOf<T, Prefix extends string = ''> = {
  [K in keyof T & string]: T[K] extends string ? `${Prefix}${K}`
    : T[K] extends readonly string[] ? `${Prefix}${K}`
    : T[K] extends object ? PathsOf<T[K], `${Prefix}${K}.`>
    : never;
}[keyof T & string];

export type TranslationKey = PathsOf<typeof translations['fr']>;
